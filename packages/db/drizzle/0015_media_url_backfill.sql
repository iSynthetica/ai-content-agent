-- Бекфіл image_url: старі рядки містять file://<abs> (напр. file:///data/images/<runId>/<draft>.png),
-- який браузер не тягне (баг зі звіту покупця). Тепер worker пише публічний mediaUrl(key) =
-- /api/media/<runId>/<draft>.<ext>, а api роздає байти (GET /v1/media). Переписуємо історичні рядки
-- у той самий формат, щоб уже згенеровані картинки одразу засвітилися без перегенерації.
--
-- Ключ — це завжди ДВА останні сегменти шляху (<runId>/<draft>.<ext>), тож витягуємо їх регуляркою
-- незалежно від того, який був IMAGE_DIR (прод: /data/images; локально: інший abs). Ідемпотентно:
-- після виконання жоден рядок не матиме префікса file://.
UPDATE "content_items"
SET "image_url" = '/api/media/' || regexp_replace("image_url", '^.*/([^/]+/[^/]+)$', '\1')
WHERE "image_url" LIKE 'file://%';
